#!/usr/bin/env bash
# Regenerate llms-full.txt — the single-fetch corpus of the whole library.
# Run after editing any reference part, prompt file, or portable prompt.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

OUT="llms-full.txt"

# Order matters: entry points, then the framework, then the prompt libraries,
# then the extension sets, then the portable prompts.
FILES=(
  "AGENTS.md"
  "SKILL.md"
  "reference/part-1-research-and-routing.md"
  "reference/part-2-library-structure-and-foundation.md"
  "reference/part-3-creative-art-direction.md"
  "reference/part-4-design-dna-styleframes.md"
  "reference/part-5-image-generation.md"
  "reference/part-6-video-generation.md"
  "reference/part-7-storyboards-motion-editing-ae-sound.md"
  "reference/part-8-asset-management-qa-workflows.md"
  "prompts/prompts-only.md"
  "prompts/standalone-prompts.md"
  "prompts/extensions/creator-talking-head-prompts.md"
  "prompts/extensions/creator-reference-locked-prompts.md"
  "prompts/extensions/creator-prompts-standalone.md"
  "prompts/extensions/ugc-avatar-prompts.md"
  "portable/system-prompt.md"
  "portable/gemini-gem-instructions.md"
  "portable/chatgpt-instructions.md"
  "portable/mini-prompt.md"
  "portable/kickoff-prompt.md"
)

for f in "${FILES[@]}"; do
  [ -f "$f" ] || { echo "build: missing $f" >&2; exit 1; }
done

BUILT="$(mktemp)"
trap 'rm -f "$BUILT"' EXIT

{
  cat <<'HEADER'
# AI Creative OS — full corpus

> Single-file edition of the AI Creative OS prompt library, for agents that can
> fetch one URL but cannot browse a repository. It concatenates the entry
> points, the 8-part reference framework, both prompt extracts, the extension
> prompt sets, and the portable prompts.
>
> House rules that apply throughout: route to one stage before answering; ask
> only what changes the deliverable; tag every claim [CONFIRMED],
> [ASSUMPTION - reason], [UNKNOWN], [PROPOSED: value], [LOCKED: value], or
> [APPROVED: value - DEC-ID]; never contradict an approved or locked element;
> keep model-specific syntax as a thin adapter; never invent tool versions,
> limits, or prices; never grant creative or client approval on the user's
> behalf; require documented consent before generating a real person's likeness.
>
> Generated by tools/build.sh — do not edit by hand.

## Contents

HEADER

  for f in "${FILES[@]}"; do
    printf -- '- %s\n' "$f"
  done
  printf '\n'

  for f in "${FILES[@]}"; do
    printf '\n\n---\n\n<!-- ===== BEGIN %s ===== -->\n\n' "$f"
    cat "$f"
    printf '\n<!-- ===== END %s ===== -->\n' "$f"
  done
} > "$BUILT"

mv "$BUILT" "$OUT"
trap - EXIT
printf 'build: wrote %s (%s bytes, %s lines)\n' \
  "$OUT" "$(wc -c < "$OUT" | tr -d ' ')" "$(wc -l < "$OUT" | tr -d ' ')"
